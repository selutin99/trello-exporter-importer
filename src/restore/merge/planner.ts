import type { ImportedBoard } from '../../import/read';
import type { Snapshot } from '../../snapshot/types';
import { IssueCode } from '../../snapshot/codes';
import type { RestoreJournal } from '../types';
import { RestoreError, RestoreErrorCode, RestoreResource, RestoreMode } from '../codes';
import { attributedComment } from '../comments';
import { Locale } from '../../i18n/types';
import { mergeRecords, recordKey } from './records';
import { matchRecord, selectedMatch } from './identity';
import { canonical, referencedKeys, resolveValue } from './values';
import { attachmentMatches } from './attachments';
import { MergeActionKind, MergeChoice, MergeConflictKind, MergeField } from './types';
import type { MergePlan, MergeRecord, MergeValue } from './types';

const copyOnChange = new Set([RestoreResource.Comment, RestoreResource.Attachment]);
const fieldNames = new Set<string>(Object.values(MergeField));

/**
 * Captures comparable active content without timestamps generated by the capture operation
 * @param snapshot - Fresh target board capture
 * @returns A deterministic in-memory baseline; never saved in the journal
 */
export function targetState(snapshot: Snapshot): string {
  return canonical({
    board: snapshot.board,
    records: mergeRecords(snapshot).sort((a, b) => a.key.localeCompare(b.key)),
  });
}

/**
 * Builds an additive merge and requires explicit decisions for identities and divergent values
 * @param imported - Validated local content
 * @param current - Fresh capture of the currently open board
 * @param decisions - Reviewed identity and field choices
 * @param previous - Same-browser journal used only for verified source-to-target mappings
 * @returns The proposed operations and unresolved conflicts; no API writes occur
 * @throws RestoreError when current board data cannot support a safe comparison
 */
export function buildMergePlan(
  imported: ImportedBoard,
  current: Snapshot,
  decisions: Record<string, string> = {},
  previous: RestoreJournal | null = null,
): MergePlan {
  if (
    current.board.closed ||
    current.capture.changedDuringCapture ||
    current.issues.some(
      (issue) =>
        issue.code === IssueCode.SectionUnavailable || issue.code === IssueCode.BoardChanged,
    )
  )
    throw new RestoreError(RestoreErrorCode.IncompleteTarget);
  return new Planner(imported, current, decisions, previous).build();
}

class Planner {
  readonly #plan: MergePlan;
  readonly #current: MergeRecord[];
  readonly #remembered: Record<string, string>;
  readonly #claimed = new Set<string>();
  readonly #skipped = new Set<string>();
  readonly #pending = new Set<string>();
  readonly #source: MergeRecord[];
  constructor(
    private readonly imported: ImportedBoard,
    current: Snapshot,
    decisions: Record<string, string>,
    previous: RestoreJournal | null,
  ) {
    this.#plan = {
      sourceBoardId: imported.snapshot.board.id,
      targetBoardId: current.board.id,
      targetState: targetState(current),
      decisions: { ...decisions },
      bindings: {},
      actions: [],
      conflicts: [],
      unresolved: 0,
      unchanged: 0,
      retained: 0,
    };
    this.#current = mergeRecords(current);
    this.#source = mergeRecords(imported.snapshot);
    this.#remembered =
      previous?.mode === RestoreMode.Merge &&
      previous.sourceBoardId === imported.snapshot.board.id &&
      previous.target?.id === current.board.id
        ? (previous.bindings ?? {})
        : {};
    // A board record supplies description data only; its destination always comes from the live SDK context.
    this.#plan.bindings[recordKey(RestoreResource.Board, imported.snapshot.board.id)] =
      current.board.id;
    for (const [key, ids] of Object.entries(previous?.commentParts ?? {})) {
      const record = this.#current.find(
        (item) => item.key === recordKey(RestoreResource.Comment, ids[0] ?? ''),
      );
      if (record && this.#remembered[key] === record.sourceId) {
        const parts = ids.map((id) => current.comments.find((item) => item.id === id)?.text);
        if (parts.every((part) => part !== undefined))
          record.fields[MergeField.Text] = parts.join('');
      }
    }
  }
  build(): MergePlan {
    for (const record of this.#source) this.#record(record);
    this.#plan.retained += this.#current.filter((record) => !this.#claimed.has(record.key)).length;
    return this.#plan;
  }
  #record(record: MergeRecord): void {
    if (record.resource === RestoreResource.Card) {
      const labels = record.fields[MergeField.Labels];
      if (Array.isArray(labels))
        record.fields[MergeField.Labels] = labels.filter(
          (label) => !this.#referencesSkipped(label),
        );
    }
    if (
      (record.parent && this.#skipped.has(record.parent)) ||
      this.#referencesSkipped(record.fields[MergeField.Value] ?? null)
    ) {
      this.#skipped.add(record.key);
      this.#plan.retained++;
      return;
    }
    const context = {
      records: this.#current,
      bindings: this.#plan.bindings,
      remembered: this.#remembered,
      claimed: this.#claimed,
    };
    const matches = matchRecord(record, context);
    let target = matches.direct;
    if (record.resource === RestoreResource.Board)
      target = this.#current.find((item) => item.resource === RestoreResource.Board) ?? null;
    const requiresChoice = matches.candidates.length > 0 || matches.incompatible;
    if (!target && requiresChoice) target = this.#identity(record, matches.candidates);
    if (this.#skipped.has(record.key)) return;
    if (!target) {
      if (!requiresChoice || this.#plan.decisions[`match/${record.key}`] === MergeChoice.Create)
        this.#create(record);
      return;
    }
    this.#claimed.add(target.key);
    this.#plan.bindings[record.key] = target.sourceId;
    this.#differences(record, target);
  }
  #referencesSkipped(value: MergeValue): boolean {
    return referencedKeys(value).some((key) => this.#skipped.has(key));
  }
  #identity(record: MergeRecord, candidates: MergeRecord[]): MergeRecord | null {
    const key = `match/${record.key}`;
    const choice = this.#plan.decisions[key];
    const selected = selectedMatch(choice, candidates);
    const valid = selected !== null || choice === MergeChoice.Create || choice === MergeChoice.Skip;
    this.#plan.conflicts.push({
      key,
      kind: MergeConflictKind.Identity,
      record,
      field: null,
      current: candidates.map((candidate) => candidate.name),
      incoming: record.name,
      candidates: candidates.map((item) => ({ id: item.sourceId, name: item.name })),
      resolution: valid ? (choice ?? null) : null,
    });
    if (!valid) this.#plan.unresolved++;
    if (choice === MergeChoice.Skip) {
      this.#skipped.add(record.key);
      this.#plan.retained++;
    }
    return selected;
  }
  #create(record: MergeRecord): void {
    this.#pending.add(record.key);
    this.#plan.actions.push({
      key: `create/${record.key}`,
      kind: MergeActionKind.Create,
      record,
      targetId: null,
      field: null,
      before: null,
      after: record.fields,
    });
  }
  #differences(record: MergeRecord, target: MergeRecord): void {
    const fields = Object.entries(record.fields).filter(
      (entry): entry is [MergeField, MergeValue] => fieldNames.has(entry[0]),
    );
    const changed =
      record.resource === RestoreResource.Attachment &&
      attachmentMatches(this.imported, record, target, this.#remembered[record.key])
        ? []
        : fields.filter(
            ([field, incoming]) =>
              !this.#equal(record, field, incoming, target.fields[field] ?? null),
          );
    if (!changed.length) {
      this.#plan.unchanged++;
      return;
    }
    if (copyOnChange.has(record.resource)) {
      this.#conflict(record, target, MergeField.Content, target.fields, record.fields, true);
      return;
    }
    for (const [field, incoming] of changed)
      this.#conflict(record, target, field, target.fields[field] ?? null, incoming, false);
  }
  #equal(
    record: MergeRecord,
    field: MergeField,
    incoming: MergeValue,
    current: MergeValue,
  ): boolean {
    if (
      (field === MergeField.Start || field === MergeField.Due) &&
      typeof incoming === 'string' &&
      typeof current === 'string'
    )
      return Date.parse(incoming) === Date.parse(current);
    if (record.resource === RestoreResource.Comment && field === MergeField.Text) {
      const comment = this.imported.snapshot.comments.find((item) => item.id === record.sourceId);
      if (
        comment &&
        Object.values(Locale).some((locale) => attributedComment(comment, locale) === current)
      )
        return true;
    }
    const left = resolveValue(incoming, this.#plan.bindings, this.#pending);
    const right = resolveValue(current, {});
    // Label assignments are sets; API response order does not represent a conflict.
    if (field === MergeField.Labels && Array.isArray(left) && Array.isArray(right))
      return (
        canonical([...left].sort((a, b) => canonical(a).localeCompare(canonical(b)))) ===
        canonical([...right].sort((a, b) => canonical(a).localeCompare(canonical(b))))
      );
    return canonical(left) === canonical(right);
  }
  #conflict(
    record: MergeRecord,
    target: MergeRecord,
    field: MergeField,
    current: MergeValue,
    incoming: MergeValue,
    copy: boolean,
  ): void {
    const key = `update/${record.key}/${field}`;
    const choice = this.#plan.decisions[key];
    const valid = choice === MergeChoice.Current || choice === MergeChoice.Snapshot;
    this.#plan.conflicts.push({
      key,
      kind: MergeConflictKind.Value,
      record,
      field,
      current,
      incoming,
      candidates: [],
      resolution: valid ? choice : null,
    });
    if (!valid) this.#plan.unresolved++;
    if (choice === MergeChoice.Current) this.#plan.retained++;
    if (choice === MergeChoice.Snapshot) {
      if (copy) this.#pending.add(record.key);
      this.#plan.actions.push({
        key,
        ...(copy ? { kind: MergeActionKind.Copy } : { kind: MergeActionKind.Update }),
        record,
        targetId: target.sourceId,
        field,
        before: current,
        after: incoming,
      });
    }
  }
}
